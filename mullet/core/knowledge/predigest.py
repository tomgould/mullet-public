"""Pre-digest pipeline — local LLM summarizes, cloud LLM reasons.

The primary cost-saving mechanism for heavy-context tasks.
Stage 1 (LOCAL tier): Heavy reading, summarization, data extraction — free
Stage 2 (MEDIUM/HIGH tier): Reasoning over lean summaries from Trove
"""

import logging
from typing import TYPE_CHECKING

if TYPE_CHECKING:
    from mullet.core.knowledge.manager import KnowledgeManager
    from mullet.core.providers.base import Provider

logger = logging.getLogger(__name__)

# Threshold: if context exceeds this many chars, pre-digest it
PREDIGEST_THRESHOLD_CHARS = 50_000


class PreDigestPipeline:
    """Two-stage processing: local LLM summarizes, cloud LLM reasons."""

    def __init__(
        self,
        local_provider: "Provider | None" = None,
        knowledge: "KnowledgeManager | None" = None,
    ):
        self.local_provider = local_provider
        self.knowledge = knowledge

    def should_predigest(self, content: str) -> bool:
        """Determine if content is heavy enough to benefit from pre-digestion."""
        if not self.local_provider:
            return False
        return len(content) > PREDIGEST_THRESHOLD_CHARS

    def predigest(
        self,
        content: str,
        instruction: str = "Summarize the key points relevant to the task",
        task_context: str = "",
    ) -> str:
        """Run local model over heavy content, return lean summary.

        If a KnowledgeManager is available, also stores the summary
        in Trove memory for later retrieval.
        """
        if not self.local_provider:
            # No local provider — return truncated content as fallback
            return content[:PREDIGEST_THRESHOLD_CHARS] + "\n\n[...content truncated, no local provider for pre-digest]"

        prompt = f"{instruction}\n\n"
        if task_context:
            prompt += f"Task context: {task_context}\n\n"
        prompt += f"Content to process ({len(content)} chars):\n\n{content}"

        # Truncate to local model's context window (rough: ~32K tokens = ~128K chars)
        max_chars = 128_000
        if len(prompt) > max_chars:
            prompt = prompt[:max_chars] + "\n\n[...truncated for local model context]"

        try:
            response = self.local_provider.create(
                messages=[
                    {"role": "system", "content": "You are a summarization assistant. Be concise and preserve key details."},
                    {"role": "user", "content": prompt},
                ],
                max_tokens=4096,
                temperature=0.3,
            )
            summary = response.content

            # Store in Trove if available
            if self.knowledge and summary:
                try:
                    self.knowledge.remember(
                        key=f"predigest_{hash(content[:100])}",
                        content=summary,
                        namespace="predigest",
                        ttl=3600,  # 1 hour TTL
                    )
                except Exception as _exc:
                    logger.warning("predigest: Failed to store summary in knowledge: %s", _exc)

            logger.info("Pre-digest: %d chars → %d chars summary", len(content), len(summary))
            return summary

        except Exception as e:
            logger.warning("Pre-digest failed: %s", e)
            return content[:PREDIGEST_THRESHOLD_CHARS] + "\n\n[...pre-digest failed, content truncated]"

    def build_cloud_prompt(self, task: str, summary: str) -> str:
        """Build prompt for cloud agent using pre-digested summary."""
        return (
            f"The following is a pre-processed summary of relevant content "
            f"(generated by a local model to save tokens):\n\n"
            f"---\n{summary}\n---\n\n"
            f"Based on this summary, {task}"
        )
